"""Original background beat made by code (no licence worries): soft kick, hats, bass and a plucky pentatonic arpeggio."""
import wave

import numpy as np

SR = 44100


def _env(n, a=.005, d=.2):
    t = np.arange(n) / SR
    return np.minimum(t / a, 1) * np.exp(-t / d)


def track(seconds, seed, path):
    rng = np.random.RandomState(seed)
    bpm = rng.choice([96, 104, 112, 120])
    beat = 60.0 / bpm
    n = int((seconds + 1) * SR)
    out = np.zeros(n)
    root = rng.choice([48, 50, 52, 53, 55])                    # MIDI root
    scale = [0, 3, 5, 7, 10, 12] if rng.rand() < .5 else [0, 2, 4, 7, 9, 12]
    f = lambda m: 440.0 * 2 ** ((m - 69) / 12)
    prog = [0, 5, 3, 7] if scale[1] == 3 else [0, 7, 9, 5]
    step = 0
    t0 = 0.0
    while t0 < seconds + 1:
        i0 = int(t0 * SR)
        beat_i = step % 4
        bar = (step // 4) % 4
        # kick on every beat
        k = int(.28 * SR)
        tt = np.arange(k) / SR
        kick = np.sin(2 * np.pi * (50 + 90 * np.exp(-tt * 30)) * tt) * np.exp(-tt * 9)
        out[i0:i0 + k] += .55 * kick[:max(0, min(k, n - i0))] if i0 < n else 0
        # hats on offbeats
        for off in (.5,):
            j = int((t0 + off * beat) * SR)
            h = int(.05 * SR)
            if j + h < n:
                out[j:j + h] += .05 * rng.randn(h) * np.exp(-np.arange(h) / SR * 70)
        # bass note on beats 1 and 3
        if beat_i % 2 == 0:
            m = root - 12 + prog[bar]
            L = int(beat * 1.9 * SR)
            if i0 + L < n:
                x = np.arange(L) / SR
                out[i0:i0 + L] += .22 * np.sin(2 * np.pi * f(m) * x) * _env(L, .01, .5)
        # arpeggio pluck on every half-beat
        for q in (0, .5):
            m = root + 12 + prog[bar] + scale[rng.randint(len(scale))]
            j = int((t0 + q * beat) * SR)
            L = int(.4 * SR)
            if j + L < n:
                x = np.arange(L) / SR
                out[j:j + L] += .1 * (np.sin(2 * np.pi * f(m) * x) + .4 * np.sin(4 * np.pi * f(m) * x)) * _env(L, .003, .12)
        t0 += beat
        step += 1
    out = out[:n]
    out = np.tanh(out * 1.4) * .8
    fade = int(.8 * SR)
    out[-fade:] *= np.linspace(1, 0, fade)
    pcm = (out * 32767).astype("<i2")
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())
    return path


def phonk(seconds, seed, path):
    """Trending gaming-reel style beat (drift/phonk): punchy kick, clap, rolling hats, gliding 808 bass, cowbell hook. Generated by code = copyright-free."""
    rng = np.random.RandomState(seed)
    bpm = int(rng.choice([128, 132, 140]))
    beat = 60.0 / bpm
    n = int((seconds + 2) * SR)
    out = np.zeros(n)
    f = lambda mi: 440.0 * 2 ** ((mi - 69) / 12)
    root = int(rng.choice([33, 34, 36, 38]))                       # bass root (A1..D2)
    riff = [0, 0, 3, 0, 5, 3, 0, -2]                                 # minor riff, one note per half-beat
    hook = [12, 15, 12, 10, 12, 15, 17, 15]
    def put(i, x):
        if 0 <= i < n:
            e = min(len(x), n - i)
            out[i:i + e] += x[:e]
    t = 0.0
    k = 0
    while t < seconds + 1.5:
        i0 = int(t * SR)
        step = k % 16                                                # 16th notes, 2 beats of 8ths per bar half
        sixteenth = beat / 4
        if step in (0, 6, 10) or (step == 14 and rng.rand() < .5):  # kick
            L = int(.28 * SR); x = np.arange(L) / SR
            put(i0, .9 * np.sin(2 * np.pi * (48 + 110 * np.exp(-x * 28)) * x) * np.exp(-x * 9))
        if step in (4, 12):                                          # clap/snare
            L = int(.18 * SR); x = np.arange(L) / SR
            put(i0, .35 * rng.randn(L) * np.exp(-x * 22) + .2 * np.sin(2 * np.pi * 190 * x) * np.exp(-x * 30))
        roll = step >= 12 and rng.rand() < .5                       # hat, with rolls at the end of the bar
        for q in ((0, .5) if roll else (0,)):
            L = int(.04 * SR); x = np.arange(L) / SR
            put(i0 + int(q * sixteenth * SR), .12 * rng.randn(L) * np.exp(-x * 120))
        if step % 2 == 0:                                            # 808 bass with glide, follows the riff
            nn = root + riff[(step // 2) % 8]
            L = int(sixteenth * 2 * SR * 1.6); x = np.arange(L) / SR
            fr = f(nn) * (1 + .5 * np.exp(-x * 30))
            put(i0, .5 * np.tanh(2 * np.sin(2 * np.pi * np.cumsum(fr) / SR)) * np.exp(-x * 3.2))
        if step % 2 == 0 and ((step // 2) % 8) not in (3, 7):       # cowbell-like hook (two detuned squares)
            nn = root + 36 + hook[(step // 2) % 8]
            L = int(.16 * SR); x = np.arange(L) / SR
            sq = np.sign(np.sin(2 * np.pi * f(nn) * x)) + np.sign(np.sin(2 * np.pi * f(nn) * 1.504 * x))
            put(i0, .06 * sq * np.exp(-x * 14))
        t += sixteenth
        k += 1
    out = np.tanh(out[:n] * 1.5) * .85
    fade = int(1.0 * SR)
    out[-fade:] *= np.linspace(1, 0, fade)
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes((out * 32767).astype("<i2").tobytes())
    return path


def pick(seconds, seed, path, folder, ffmpeg):
    """If the folder `music/` holds royalty-free tracks (mp3/wav/m4a) use one of them (trimmed/looped to length); otherwise the generated beat."""
    import random
    import subprocess
    files = sorted(p for p in folder.glob("*") if p.suffix.lower() in (".mp3", ".wav", ".m4a", ".ogg"))
    if files:
        src = random.Random(seed).choice(files)
        subprocess.run([ffmpeg, "-y", "-loglevel", "error", "-stream_loop", "-1", "-i", str(src), "-t", f"{seconds + 1:.1f}", "-ar", "44100", "-ac", "1",
                        "-af", f"afade=t=out:st={max(0, seconds - 1):.1f}:d=1.2", str(path)], check=True)
        return f"music/{src.name}"
    phonk(seconds, seed, path)
    return "generated phonk beat"
